#!/usr/bin/env bash
# Unbiased MD of LBT1-CONH2 + Ln(III) (GROMACS 2018-2020): minimisation, 5 ns equilibration, 200 ns production,
# then two energy-group reruns for the pairwise interaction energies used as Library 1 descriptors.
#
#   ./run_unbiased.sh [ION]        ION = La, Ce, ..., Lu (default Tb); results go to runs/LBT1-CONH2_<ION>/
#
# The archived Tb system (structures/LBT1-CONH2-Tb_solvated.gro, topology/topol_LBT1-CONH2_Tb.top) is used as the
# template; other lanthanides are obtained by renaming the ion (parameters in forcefield/.../lanthanides-2.itp).
# How the archived system was built: the peptide topology came from
#   gmx pdb2gmx -f structures/LBT1-CONH2.pdb -water tip3p -ff charmm36-jul2021 -ignh -ter
# the ion was placed at its 1TJB position (structures/LBT1-CONH2-Tb.pdb), and the complex was solvated in TIP3P
# water in a cubic box with NaCl at 0.1 M (see the .gro/.top files for the exact box and molecule counts).
set -euo pipefail
ION=${1:-Tb}
GMX=${GMX:-gmx}
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUN="$HERE/runs/LBT1-CONH2_${ION}"
mkdir -p "$RUN" && cd "$RUN"

# --- system files (ion renamed if needed); the force field is linked next to the topology
ln -sfn "$HERE/forcefield/charmm36-jul2021.ff" charmm36-jul2021.ff
cp "$HERE/topology/posre.itp" .
sed "s/^Tb3+ /${ION}3+ /" "$HERE/topology/topol_LBT1-CONH2_Tb.top" > topol.top
awk -v ion="$ION" 'NR > 2 && substr($0, 6, 5) ~ /^Tb/ {
        $0 = substr($0, 1, 5) sprintf("%-5s%5s", ion, ion) substr($0, 16) } { print }' \
    "$HERE/structures/LBT1-CONH2-Tb_solvated.gro" > solvated.gro

# --- minimisation, equilibration, production
$GMX grompp -f "$HERE/mdp/minim.mdp" -c solvated.gro -p topol.top -o em.tpr -maxwarn 1
$GMX mdrun -deffnm em
$GMX grompp -f "$HERE/mdp/equilibration_npt_5ns.mdp" -c em.gro -p topol.top -o md.tpr -maxwarn 1
$GMX mdrun -deffnm md
$GMX grompp -f "$HERE/mdp/production_200ns.mdp" -c md.gro -t md.cpt -p topol.top -o md2.tpr -maxwarn 1
$GMX mdrun -deffnm md2

# --- energy-group reruns (groups: ion, ligating residues 3/5/7/9/11/14, water). Default groups 13 (the ion) and
#     1 (Protein) are those generated by make_ndx for this topology.
printf '1 & r 3\n1 & r 5\n1 & r 7\n1 & r 9\n1 & r 11\n1 & r 14\nname 13 Ln\nname 19 r3\nname 20 r5\nname 21 r7\nname 22 r9\nname 23 r11\nname 24 r14\nq\n' \
    | $GMX make_ndx -f md2.gro -o energy_groups.ndx
for kind in lj coulomb; do                 # LJ-SR from production settings, Coul-SR from a 2.35 nm plain cut-off
    $GMX grompp -f "$HERE/mdp/rerun_${kind}.mdp" -c md2.gro -p topol.top -n energy_groups.ndx -o rerun_${kind}.tpr -maxwarn 1
    $GMX mdrun -rerun md2.trr -s rerun_${kind}.tpr -deffnm rerun_${kind}
done
echo "Done. Analyse with ../../03_unbiased_md_analysis/gromacs_analysis.sh $RUN $ION"
